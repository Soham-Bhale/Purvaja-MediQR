let inMemoryAppointments: Appointment[] = [...INITIAL_APPOINTMENTS];

export function getStoredAppointments(): Appointment[] {
  if (typeof window === 'undefined') return inMemoryAppointments;
  try {
    const raw = localStorage.getItem(APPOINTMENTS_STORAGE_KEY);
    if (raw) {
      const parsed: Appointment[] = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (err) {
    console.error('Failed reading appointments from storage:', err);
  }
  // Initialize with initial appointments if empty
  persistAppointments(inMemoryAppointments);
  return inMemoryAppointments;
}

export function persistAppointments(appointments: Appointment[]): void {
  inMemoryAppointments = [...appointments];
  if (typeof window !== 'undefined') {
    try {
      localStorage.setItem(APPOINTMENTS_STORAGE_KEY, JSON.stringify(appointments));
      window.dispatchEvent(new CustomEvent('mediqr_appointment_updated', { detail: appointments }));
    } catch (err) {
      console.error('Failed saving appointments:', err);
    }
  }
}

export function saveAppointment(appointment: Appointment): Appointment {
  const all = getStoredAppointments();
  const existingIdx = all.findIndex((a) => a.id === appointment.id);
  if (existingIdx >= 0) {
    all[existingIdx] = appointment;
  } else {
    all.unshift(appointment);
  }
  persistAppointments(all);
  return appointment;
}

export function getAppointmentById(id: string): Appointment | null {
  const all = getStoredAppointments();
  return all.find((a) => a.id.toLowerCase() === id.trim().toLowerCase()) || null;
}

export function getAppointmentsForDoctor(doctorAddressOrName: string): Appointment[] {
  const all = getStoredAppointments();
  const clean = doctorAddressOrName.toLowerCase();
  return all.filter(
    (a) =>
      a.doctorId.toLowerCase() === clean ||
      a.doctorName.toLowerCase().includes(clean)
  );
}

export function updateAppointmentStatus(
  id: string,
  status: Appointment['status'],
  extra?: Partial<Appointment>
): Appointment | null {
  const all = getStoredAppointments();
  const index = all.findIndex((a) => a.id === id);
  if (index === -1) return null;

  const updated: Appointment = {
    ...all[index],
    ...extra,
    status,
  };
  all[index] = updated;
  persistAppointments(all);
  return updated;
}
