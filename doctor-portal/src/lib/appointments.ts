let inMemoryAppointments: Appointment[] = [...INITIAL_APPOINTMENTS];

export function clearAllTestAppointments(): void {
  inMemoryAppointments = [...INITIAL_APPOINTMENTS];
  if (typeof window !== 'undefined') {
    try {
      localStorage.setItem(APPOINTMENTS_STORAGE_KEY, JSON.stringify(inMemoryAppointments));
      window.dispatchEvent(new CustomEvent('mediqr_appointment_updated', { detail: inMemoryAppointments }));
    } catch (err) {
      console.error('Failed clearing appointments:', err);
    }
  }
}

export function getStoredAppointments(): Appointment[] {
  if (typeof window === 'undefined') return inMemoryAppointments;
  try {
    const raw = localStorage.getItem(APPOINTMENTS_STORAGE_KEY);
    if (raw) {
      const parsed: Appointment[] = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (err) {
    console.error('Failed reading appointments from storage:', err);
  }
  // Initialize with initial appointments if empty
  persistAppointments(inMemoryAppointments);
  return inMemoryAppointments;
}

export function persistAppointments(appointments: Appointment[]): void {
  inMemoryAppointments = [...appointments];
  if (typeof window !== 'undefined') {
    try {
      localStorage.setItem(APPOINTMENTS_STORAGE_KEY, JSON.stringify(appointments));
      window.dispatchEvent(new CustomEvent('mediqr_appointment_updated', { detail: appointments }));
    } catch (err) {
      console.error('Failed saving appointments:', err);
    }
  }
}

export function saveAppointment(appointment: Appointment): Appointment {
  const all = getStoredAppointments();
  const existingIdx = all.findIndex((a) => a.id === appointment.id);
  if (existingIdx >= 0) {
    all[existingIdx] = appointment;
  } else {
    all.unshift(appointment);
  }
  persistAppointments(all);
  return appointment;
}

export function getAppointmentById(id: string): Appointment | null {
  const all = getStoredAppointments();
  return all.find((a) => a.id.toLowerCase() === id.trim().toLowerCase()) || null;
}

/**
 * STRICT DOCTOR ISOLATION:
 * Only the appointed doctor at that specific hospital can see their assigned patient requests!
 * No doctor or role switch will leak another doctor's appointments.
 */
export function getAppointmentsForDoctor(doctorAddressOrName: string): Appointment[] {
  const all = getStoredAppointments();
  if (!doctorAddressOrName) return [];
  const clean = doctorAddressOrName.toLowerCase().trim();
  
  return all.filter(
    (a) =>
      a.doctorId.toLowerCase() === clean ||
      clean.includes(a.doctorId.toLowerCase()) ||
      a.doctorId.toLowerCase().includes(clean)
  );
}

/**
 * Get all appointments booked by a specific authenticated patient user
 */
export function getAppointmentsForUser(emailOrUserId: string): Appointment[] {
  const all = getStoredAppointments();
  if (!emailOrUserId) return [];
  const clean = emailOrUserId.toLowerCase().trim();
  return all.filter(
    (a) =>
      (a.userId && a.userId.toLowerCase() === clean) ||
      (a.email && a.email.toLowerCase() === clean)
  );
}

/**
 * Request an appointment reschedule (Strictly limited to 1 time per policy)
 */
export function rescheduleAppointment(
  appointmentId: string,
  newDate: string,
  newTimeSlot: string
): { success: boolean; error?: string; appointment?: Appointment } {
  const all = getStoredAppointments();
  const idx = all.findIndex((a) => a.id === appointmentId);
  if (idx < 0) {
    return { success: false, error: 'Appointment not found.' };
  }
  const apt = all[idx];
  if (apt.hasRescheduled || (apt.rescheduleCount && apt.rescheduleCount >= 1)) {
    return { success: false, error: 'Policy Limit Reached: An appointment can only be rescheduled once.' };
  }
  apt.appointmentDate = newDate;
  apt.timeSlot = newTimeSlot;
  apt.hasRescheduled = true;
  apt.rescheduleCount = (apt.rescheduleCount || 0) + 1;
  all[idx] = apt;
  persistAppointments(all);
  return { success: true, appointment: apt };
}

export function updateAppointmentStatus(
  id: string,
  status: Appointment['status'],
  extra?: Partial<Appointment>
): Appointment | null {
  const all = getStoredAppointments();
  const index = all.findIndex((a) => a.id === id);
  if (index === -1) return null;

  const updated: Appointment = {
    ...all[index],
    ...extra,
    status,
  };
  all[index] = updated;
  persistAppointments(all);
  return updated;
}
